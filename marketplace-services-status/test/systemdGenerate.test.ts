// The unit PATH decides which node every `#!/usr/bin/env node` shim in a repo's node_modules/.bin
// runs under, so the three spellings services.json may use for the nvm directory all have to land
// as the same absolute path systemd can read — it expands nothing itself.
describe('the nvm directory', () => {
  const pathLine = (content: string): string => line(content, 'Environment=PATH=');

  it('expands a bare ~ to the home directory', async () => {
    await boot({ config: config({ nvmDir: '~' }) });

    expect(pathLine(unit('api.service'))).toBe(
      'Environment=PATH=/home/tester/versions/node/v24.18.0/bin:/usr/local/bin:/usr/bin:/bin'
    );
  });

  it('expands a leading ~/ and keeps the rest of the path', async () => {
    await boot();

    expect(pathLine(unit('api.service'))).toBe(
      'Environment=PATH=/home/tester/.nvm/versions/node/v24.18.0/bin:/usr/local/bin:/usr/bin:/bin'
    );
  });

  it('leaves an absolute nvm directory alone', async () => {
    await boot({ config: config({ nvmDir: '/opt/nvm' }) });

    expect(pathLine(unit('api.service'))).toBe(
      'Environment=PATH=/opt/nvm/versions/node/v24.18.0/bin:/usr/local/bin:/usr/bin:/bin'
    );
  });
});

describe('a monitored service unit', () => {
  it('carries the banner, the group title and the target it is part of', async () => {
    await boot();

    const content = unit('api.service');

    expect(content.startsWith(BANNER)).toBe(true);
    expect(content).toContain('Description=API (Core) — The API service');
    expect(content).toContain(`Documentation=file://${path.join(workspaceRoot, 'BEs/dev/api')}`);
    expect(content).toContain('PartOf=marketplace.target');
    expect(content).toContain(`WorkingDirectory=${path.join(workspaceRoot, 'BEs/dev/api')}`);
    expect(content).toContain('SyslogIdentifier=api');
  });

  // Without [Install] `systemctl --user enable` refuses the unit outright, which is what makes
  // "never starts at boot" structural. An [Install] section here would make it a convention.
  // Read line by line, never as a substring: the file explains the absence in a comment that
  // spells the word, so `not.toContain` on the whole text fails on the explanation.
  it('has no [Install] section and cannot be enabled', async () => {
    await boot();

    expect(unit('api.service').split('\n')).not.toContain('[Install]');
  });

  // Restart=no and the three SuccessExitStatus spellings are one mechanism: a stop must read
  // clean and a crash must read 'failed', because the page tells them apart by exactly that.
  it('stays failed when it crashes and clean when it is stopped', async () => {
    await boot();

    const content = unit('api.service');

    expect(content).toContain('Restart=no');
    expect(content).toContain('KillMode=control-group');
    expect(content).toContain('SuccessExitStatus=143 15 SIGTERM');
  });
});

describe('the ExecStart command', () => {
  const execLine = (content: string): string => line(content, 'ExecStart=');

  // `exec` is the load-bearing word: it replaces the shell, so vite or tsx becomes the unit's
  // MainPID and takes SIGTERM directly. Without it systemd signals /bin/sh and the real process
  // is orphaned. Everything before the last segment stays ahead of it and still fails the unit.
  it('execs the last segment and leaves the ones before it in front', async () => {
    await boot({ packages: { 'BEs/dev/api': { scripts: { dev: 'tsc --noEmit && vite dev' } } } });

    const content = unit('api.service');

    expect(execLine(content)).toBe("ExecStart=/bin/sh -c 'tsc --noEmit && exec vite dev'");
    expect(content).toContain(
      '# from BEs/dev/api/package.json scripts.dev: tsc --noEmit && vite dev'
    );
  });

  it('resolves a bare binary against the repo node_modules/.bin when it is there', async () => {
    await boot({ bins: [repoBin('BEs/dev/api', 'vite')] });

    expect(execLine(unit('api.service'))).toBe(
      `ExecStart=/bin/sh -c 'exec ${repoBin('BEs/dev/api', 'vite')}'`
    );
  });

  // The unit PATH carries the pinned node and nothing repo-local, so a name that is not there is
  // left as written rather than rewritten into a path that does not exist.
  it('leaves a command alone when the repo has no such local binary', async () => {
    await boot({ packages: { 'BEs/dev/api': { scripts: { dev: 'node server.js' } } } });

    expect(execLine(unit('api.service'))).toBe("ExecStart=/bin/sh -c 'exec node server.js'");
  });

  // npx would re-resolve the binary the line above just resolved, and put another process between
  // systemd and the target.
  it('drops a leading npx and resolves what it was going to run', async () => {
    await boot({
      packages: { 'BEs/dev/api': { scripts: { dev: 'npx vite --host' } } },
      bins: [repoBin('BEs/dev/api', 'vite')]
    });

    expect(execLine(unit('api.service'))).toBe(
      `ExecStart=/bin/sh -c 'exec ${repoBin('BEs/dev/api', 'vite')} --host'`
    );
  });

  it('drops an empty segment left by a trailing &&', async () => {
    await boot({ packages: { 'BEs/dev/api': { scripts: { dev: 'tsc && ' } } } });

    expect(execLine(unit('api.service'))).toBe("ExecStart=/bin/sh -c 'exec tsc'");
  });

  // A segment is split on whitespace to find its binary (parts[0]) and rejoined with a single
  // space. Splitting on a run of whitespace as one delimiter, rather than one whitespace character
  // at a time, is what stops a double space (or a stray tab) from leaving an empty '' element that
  // rejoining would turn back into extra, meaningless whitespace in the final command.
  it('collapses a run of whitespace inside a segment to one space', async () => {
    await boot({ packages: { 'BEs/dev/api': { scripts: { dev: 'vite  --host' } } } });

    expect(execLine(unit('api.service'))).toBe("ExecStart=/bin/sh -c 'exec vite --host'");
  });
});

describe('the scripts it refuses to translate', () => {
  it('names the script and the file when the repo does not define it', async () => {
    await expect(boot({ packages: { 'BEs/dev/api': { scripts: { start: 'vite' } } } })).rejects
      .toThrow(
        `api: no "dev" script in ${path.join(workspaceRoot, 'BEs/dev/api', 'package.json')}. ` +
          'services.json names a script that repo does not define.'
      );
  });

  it('says the same when the repo has no package.json at all', async () => {
    await expect(boot({ packages: {} })).rejects.toThrow('api: no "dev" script in');
  });

  it('says the same when the package.json has no scripts block', async () => {
    await expect(boot({ packages: { 'BEs/dev/api': { name: 'api' } } })).rejects.toThrow(
      'api: no "dev" script in'
    );
  });

  // Guessing at a shell construct this generator does not parse would produce a unit that runs
  // something other than what the repo's script says, and nothing downstream would notice — so the
  // message has to say that, in full, not just name the script. `.rejects.toThrow(string)` only
  // checks a substring, which would still pass with the explanation blanked out, so the exact
  // message is asserted directly off the caught error instead.
  it('refuses shell syntax it does not parse, quoting the script back and explaining why', async () => {
    let caught: unknown;

    try {
      await boot({ packages: { 'BEs/dev/api': { scripts: { dev: 'vite || true' } } } });
    } catch (err) {
      caught = err;
    }

    expect(caught).toBeInstanceOf(Error);
    expect((caught as Error).message).toBe(
      'api: the "dev" script uses shell syntax this generator does not parse ("vite || true"). ' +
        'Simplify the script, or teach buildExecCommand about it — guessing here would silently ' +
        'produce a unit that runs the wrong thing.'
    );
  });

  // ⚠️ The guard masks `&&` before testing for a bare `&`, and this is the case that says so: an
  // unmasked test matches the second `&` of every `&&` and rejects every chained script there is.
  it('does not mistake the && it handles for the & it refuses', async () => {
    await boot({ packages: { 'BEs/dev/api': { scripts: { dev: 'tsc && vite' } } } });

    expect(unit('api.service')).toContain("ExecStart=/bin/sh -c 'tsc && exec vite'");
  });
});


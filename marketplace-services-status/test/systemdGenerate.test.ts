/**
 * `systemd/generate.mjs` — `yarn systemd:generate`, and the one JavaScript file in this repo
 * outside `src/`.
 *
 * It is a script, not a module: no exports, three hundred lines of top-level `main()`. So the only
 * way to exercise it is to import it for its side effects, once per case, with the filesystem and
 * `process.argv` replaced — which is what `boot()` below does. What it *is*, though, is the thing
 * that decides what `systemctl --user start` actually runs for thirteen units, so every line it
 * writes into a unit file is a claim worth asserting.
 *
 * ⚠️ **`node:fs` is mocked rather than pointed at a temp tree.** The generator resolves the repos
 * it reads out of `services.json`'s `workspaceRoot`, so a real-filesystem test would read the
 * fifteen sibling repos' own `package.json` files and go red when one of them edited a script it
 * has nothing to do with. The fixtures here are the shapes, and the real `services.json` is
 * checked by `test/config.test.ts` against the same file the monitor reads.
 *
 * ⚠️ **`vi.resetModules()` before every import is what makes the cases independent.** A module is
 * evaluated once per registry, so without it the second `import()` returns the first case's cached
 * module, writes nothing, and asserts nothing at all — while passing.
 */
import path from 'node:path';
import { fileURLToPath } from 'node:url';

import { afterEach, beforeEach, describe, expect, it, vi } from 'vitest';

const fs = vi.hoisted(() => ({
  existsSync: vi.fn(),
  mkdirSync: vi.fn(),
  readFileSync: vi.fn(),
  writeFileSync: vi.fn()
}));

const os = vi.hoisted(() => ({ homedir: vi.fn() }));

vi.mock('node:fs', () => fs);
vi.mock('node:os', () => ({ default: os }));

// The three directories the generator derives from its own location, derived here the same way and
// from this file's own location — a literal would be a second copy of the layout to keep in step.
const systemdDir = fileURLToPath(new URL('../systemd', import.meta.url));
const repoDir = path.resolve(systemdDir, '..');
const workspaceRoot = path.resolve(repoDir, '..');
const defaultOutDir = path.join(systemdDir, 'units');

const BANNER =
  '# GENERATED by marketplace-services-status/systemd/generate.mjs — do not edit by hand.';

/** Where a monitored repo's `node_modules/.bin` entry would be, for the `existsSync` fixture. */
const repoBin = (repo: string, name: string): string =>
  path.join(workspaceRoot, repo, 'node_modules', '.bin', name);

/** The same, for this repo — the monitor unit resolves its own command against its own bin dir. */
const ownBin = (name: string): string => path.join(repoDir, 'node_modules', '.bin', name);

const service = (patch: Record<string, unknown> = {}): Record<string, unknown> => ({
  id: 'api',
  label: 'API',
  repo: 'BEs/dev/api',
  kind: 'backend',
  script: 'dev',
  port: 4027,
  path: '/api',
  description: 'The API service',
  ...patch
});

const config = (patch: Record<string, unknown> = {}): Record<string, unknown> => ({
  workspaceRoot: '..',
  nodeVersion: '24.18.0',
  nvmDir: '~/.nvm',
  unitTarget: 'marketplace.target',
  monitorUnit: 'marketplace-status.service',
  groups: [{ id: 'core', title: 'Core', description: 'The core tier', services: [service()] }],
  ...patch
});

const DEFAULT_PACKAGES: Record<string, unknown> = { 'BEs/dev/api': { scripts: { dev: 'vite' } } };
const DEFAULT_MONITOR = { scripts: { start: 'node dist/server.js' } };

interface BootOptions {
  config?: Record<string, unknown>;
  packages?: Record<string, unknown>;
  monitor?: unknown;
  bins?: string[];
  argv?: string[];
  /**
   * Overrides `process.argv` outright instead of appending `argv` after the usual
   * `['/usr/bin/node', '.../generate.mjs']` prefix — for the one test that has to control what
   * lands at index 0 and 1, where the normal helper never would.
   */
  rawArgv?: string[];
}

const realArgv = process.argv;

let log: ReturnType<typeof vi.spyOn>;

beforeEach(() => {
  fs.existsSync.mockReset();
  fs.mkdirSync.mockReset();
  fs.readFileSync.mockReset();
  fs.writeFileSync.mockReset();
  os.homedir.mockReturnValue('/home/tester');
  log = vi.spyOn(console, 'log').mockImplementation(() => undefined);
});

afterEach(() => {
  process.argv = realArgv;
  vi.restoreAllMocks();
});

/** Run the generator once against a fixture filesystem and a fixture command line. */
const boot = async ({
  config: cfg = config(),
  packages = DEFAULT_PACKAGES,
  monitor = DEFAULT_MONITOR,
  bins = [],
  argv = [],
  rawArgv
}: BootOptions = {}): Promise<void> => {
  const files = new Map<string, string>();

  files.set(path.join(repoDir, 'services.json'), JSON.stringify(cfg));
  files.set(path.join(repoDir, 'package.json'), JSON.stringify(monitor));
  for (const [repo, pkg] of Object.entries(packages)) {
    files.set(
      path.join(workspaceRoot, repo, 'package.json'),
      typeof pkg === 'string' ? pkg : JSON.stringify(pkg)
    );
  }

  fs.readFileSync.mockImplementation((p: unknown) => {
    const found = files.get(String(p));

    if (found === undefined) {
      throw new Error(`ENOENT: no such file or directory, open '${String(p)}'`);
    }

    return found;
  });
  fs.existsSync.mockImplementation((p: unknown) => bins.includes(String(p)));

  process.argv = rawArgv ?? ['/usr/bin/node', path.join(systemdDir, 'generate.mjs'), ...argv];

  vi.resetModules();
  await import('../systemd/generate.mjs');
};

/** Every file the run wrote, by absolute path. */
const written = (): Map<string, string> =>
  new Map(fs.writeFileSync.mock.calls.map((call) => [String(call[0]), String(call[1])]));

/** One written unit by name, or a failure that says which — never an undefined dereference. */
const unit = (name: string, outDir: string = defaultOutDir): string => {
  const found = written().get(path.join(outDir, name));

  if (found === undefined) {
    throw new Error(`nothing was written to ${path.join(outDir, name)}`);
  }

  return found;
};

/** The single line of a unit starting with `prefix`, for the assertions that are about one line. */
const line = (content: string, prefix: string): string => {
  const found = content.split('\n').filter((l) => l.startsWith(prefix));

  if (found.length !== 1) {
    throw new Error(`expected exactly one ${prefix}… line, found ${found.length}`);
  }

  return found[0];
};

const TWO_GROUPS = config({
  groups: [
    {
      id: 'core',
      title: 'Core',
      description: 'The core tier',
      services: [service(), service({ id: 'web', label: 'Web', repo: 'FEs/web', script: 'dev' })]
    },
    {
      id: 'edge',
      title: 'Edge',
      description: 'The edge tier',
      services: [service({ id: 'gw', label: 'Gateway', repo: 'BEs/dev/gw', script: 'serve' })]
    }
  ]
});

const TWO_GROUPS_PACKAGES: Record<string, unknown> = {
  'BEs/dev/api': { scripts: { dev: 'vite' } },
  'FEs/web': { scripts: { dev: 'vite' } },
  'BEs/dev/gw': { scripts: { serve: 'tsx watch src/index.ts' } }
};

describe('the unit generator', () => {
  it('writes one unit per service across every group, plus the target and the monitor', async () => {
    await boot({ config: TWO_GROUPS, packages: TWO_GROUPS_PACKAGES });

    expect(fs.mkdirSync).toHaveBeenCalledWith(defaultOutDir, { recursive: true });
    expect([...written().keys()]).toStrictEqual([
      path.join(defaultOutDir, 'api.service'),
      path.join(defaultOutDir, 'web.service'),
      path.join(defaultOutDir, 'gw.service'),
      path.join(defaultOutDir, 'marketplace.target'),
      path.join(defaultOutDir, 'marketplace-status.service')
    ]);
    expect(log).toHaveBeenCalledWith(`Wrote 5 unit files to ${defaultOutDir}`);
  });

  it('writes to --out instead, resolved against the working directory', async () => {
    const outDir = path.resolve('build/units');

    await boot({ argv: ['--out', 'build/units'] });

    expect(fs.mkdirSync).toHaveBeenCalledWith(outDir, { recursive: true });
    expect(unit('api.service', outDir)).toContain(BANNER);
    expect(written().has(path.join(defaultOutDir, 'api.service'))).toBe(false);
  });

  it('ignores an argument it does not know', async () => {
    await boot({ argv: ['--verbose'] });

    expect(fs.mkdirSync).toHaveBeenCalledWith(defaultOutDir, { recursive: true });
  });

  // main() must hand parseArgs() only the caller-supplied arguments — process.argv[0] and [1]
  // are always the node binary and this script's own path, never something a user typed. Proven
  // here with a two-element process.argv standing in for exactly that pair: if main() forgot to
  // slice them off, this '--out' would be seen as index 0 of the args and 'nonsense' taken as its
  // value, moving outDir away from the default.
  it('never mistakes the interpreter path or this script path for a --out flag', async () => {
    await boot({ rawArgv: ['--out', 'nonsense'] });

    expect(fs.mkdirSync).toHaveBeenCalledWith(defaultOutDir, { recursive: true });
  });

  // Falling back to the default output directory here would write thirteen units somewhere the
  // caller did not ask for, which `install.sh` would then install.
  it('refuses --out with nothing after it rather than falling back to the default', async () => {
    await expect(boot({ argv: ['--out'] })).rejects.toThrow('--out requires a directory argument');

    expect(fs.mkdirSync).not.toHaveBeenCalled();
    expect(fs.writeFileSync).not.toHaveBeenCalled();
  });
});

// Every read and write here goes through Buffer<->string once, at a boundary humans then read
// (a unit file, a diagnostic in a thrown Error). Dropping the encoding argument would still run —
// readFileSync/writeFileSync default to a Buffer/binary — so only the exact call arguments prove
// 'utf8' is actually there, not just that some content came back.
describe('the encoding every read and write asks for', () => {
  it('reads services.json and a monitored repo package.json as utf8, not binary', async () => {
    await boot();

    expect(fs.readFileSync).toHaveBeenCalledWith(path.join(repoDir, 'services.json'), 'utf8');
    expect(fs.readFileSync).toHaveBeenCalledWith(
      path.join(workspaceRoot, 'BEs/dev/api', 'package.json'),
      'utf8'
    );
  });

  it('writes every generated unit file as utf8, not binary', async () => {
    await boot();

    expect(fs.writeFileSync).toHaveBeenCalledWith(
      path.join(defaultOutDir, 'api.service'),
      expect.any(String),
      'utf8'
    );
    expect(fs.writeFileSync).toHaveBeenCalledWith(
      path.join(defaultOutDir, 'marketplace.target'),
      expect.any(String),
      'utf8'
    );
    expect(fs.writeFileSync).toHaveBeenCalledWith(
      path.join(defaultOutDir, 'marketplace-status.service'),
      expect.any(String),
      'utf8'
    );
  });
});


describe('the monitor unit', () => {
  // The one generated unit that may be enabled: nothing else can start the control page, and the
  // page is how anything else gets started. Enabling it enables none of the units it monitors.
  it('is the only one with an [Install] section, and restarts itself', async () => {
    await boot();

    const content = unit('marketplace-status.service');

    expect(content).toContain('[Install]\nWantedBy=default.target');
    expect(content).toContain('Restart=on-failure');
    expect(content).toContain('RestartSec=2');
    expect(content).toContain('Environment=NODE_ENV=production');
    expect(content).toContain(`WorkingDirectory=${repoDir}`);
    expect(content).toContain('SyslogIdentifier=marketplace-status');
  });

  it('takes its own command from its own package.json, exec and all', async () => {
    await boot({
      monitor: { scripts: { start: 'tsc && node dist/server.js' } },
      bins: [ownBin('tsc')]
    });

    const content = unit('marketplace-status.service');

    expect(line(content, 'ExecStart=')).toBe(
      `ExecStart=/bin/sh -c '${ownBin('tsc')} && exec node dist/server.js'`
    );
    expect(content).toContain(
      '# from marketplace-services-status/package.json scripts.start: tsc && node dist/server.js'
    );
  });

  // The monitor unit is built through the same buildExecCommand() as every other unit, passed a
  // synthetic { id: 'marketplace-status', script: 'start' } rather than a services.json entry. If
  // this repo's own package.json ever lost its start script, the error has to name it by that id —
  // an id no services.json service ever carries — not by some other repo's id.
  it("names itself 'marketplace-status', not a service id, when its own start script is missing", async () => {
    await expect(boot({ monitor: { scripts: {} } })).rejects.toThrow(
      `marketplace-status: no "start" script in ${path.join(repoDir, 'package.json')}.`
    );
  });
});
